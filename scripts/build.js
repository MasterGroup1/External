// Builds the static site into dist/ and writes dist/config.js from environment
// variables, so no Supabase credentials live in the source. Vercel runs this
// on every deploy (see vercel.json); locally it also reads a .env file if one
// exists. No dependencies — plain Node.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const dist = path.join(root, 'dist');

// Minimal .env loader for local builds; real environment variables win.
const envFile = path.join(root, '.env');
if (fs.existsSync(envFile)) {
  for (const line of fs.readFileSync(envFile, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m && !(m[1] in process.env)) process.env[m[1]] = m[2].replace(/^(['"])(.*)\1$/, '$2');
  }
}

const supabaseUrl = (process.env.SUPABASE_URL || '').trim();
const supabaseAnonKey = (process.env.SUPABASE_ANON_KEY || '').trim();

if (!supabaseUrl || !supabaseAnonKey) {
  const msg = 'SUPABASE_URL and SUPABASE_ANON_KEY must be set (see .env.example).';
  // Fail the deploy on Vercel rather than shipping a dashboard that can't save.
  if (process.env.VERCEL) { console.error('Build failed: ' + msg); process.exit(1); }
  console.warn('Warning: ' + msg + ' Building anyway — the dashboard will run offline.');
}
if (supabaseUrl && !/^https:\/\/[a-z0-9-]+\.supabase\.co\/?$/i.test(supabaseUrl)) {
  console.warn('Warning: SUPABASE_URL does not look like https://<project-ref>.supabase.co');
}

fs.rmSync(dist, { recursive: true, force: true });
fs.mkdirSync(dist);
for (const file of ['index.html', 'styles.css', 'script.js']) {
  fs.copyFileSync(path.join(root, file), path.join(dist, file));
}

const config = { supabaseUrl: supabaseUrl.replace(/\/$/, ''), supabaseAnonKey };
fs.writeFileSync(
  path.join(dist, 'config.js'),
  '// Generated by scripts/build.js — do not edit or commit.\n' +
  'window.SMS_EDGE_CONFIG = ' + JSON.stringify(config, null, 2) + ';\n'
);

console.log('Built dist/ (Supabase ' + (supabaseUrl ? 'configured: ' + config.supabaseUrl : 'NOT configured') + ')');
